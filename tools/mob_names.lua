-- Writes AllinOneGuide\Data\MobNames.lua: NPC id -> English creature name, only for the mobs the shipped guide
-- packs send the player to kill or loot (the `npc` of an objective step, and every `targetNpc`). The target button
-- (UI\TargetButton.lua) builds its "/targetexact <name>" line from this static table only (never from units,
-- nameplates or the combat log: plans\guide-window-look\tos-target.md).
-- Source: a LOCAL CMaNGOS classic-db SQL dump (https://github.com/cmangos/classic-db, GPL-3.0), read as TEXT
-- only. Only `creature_template` Entry and Name are read, so every name is a creature's (never a player's).
-- Names are cleaned here too: no ; [ ] or line breaks, at most 60 characters (the addon cleans them again).
-- Run from the repository folder:
--   luajit tools/mob_names.lua <ClassicDB.sql> [--routes AllinOneGuide/Routes] [--out AllinOneGuide/Data/MobNames.lua]
--   [--check]   write nothing; fail when the file differs (or is missing)
-- Library mode: local MN = loadfile("tools/mob_names.lua")("--lib")
--   MN.PackMobs(texts) -> sorted ids     MN.ReadNames(path, want) -> { [npc] = name }
--   MN.Clean(name) -> name or nil        MN.Text(map, ids) -> file text
local argv = { ... }
local MN = { MAX = 60 }

-- ------------------------------------------------------------------ the mobs the packs name
-- A compiled row: id|type|quest|npc|map|x|y|r|text|da|flags|cond|src|extra (texts never hold "|").
local function Fields(row)
    local f, i = {}, 1
    for part in (row .. "|"):gmatch("([^|]*)|") do f[i] = part i = i + 1 end
    return f
end

function MN.PackMobs(texts)
    local set = {}
    for _, text in ipairs(texts) do
        for row in text:gmatch('\n%s*"([^"\n]*)",?') do
            if row:find("|", 1, true) and select(2, row:gsub("|", "")) >= 12 then
                local f = Fields(row)
                local npc = tonumber(f[4])
                if f[2] == "objective" and npc and npc > 0 then set[npc] = true end
                local t = f[14] and tonumber(f[14]:match("targetNpc=(%d+)"))
                if t and t > 0 then set[t] = true end
            end
        end
    end
    local ids = {}
    for id in pairs(set) do ids[#ids + 1] = id end
    table.sort(ids)
    return ids
end

-- The same cleaning as the addon's (UI\TargetButton.lua TB.Clean): no macro separators or line breaks.
function MN.Clean(name)
    if type(name) ~= "string" then return nil end
    name = name:gsub("[;%[%]\r\n%c]", ""):gsub("^%s+", ""):gsub("%s+$", "")
    if name == "" or #name > MN.MAX then return nil end
    return name
end

-- ------------------------------------------------------------------ the SQL dump
-- One field from position i (a quoted string with \ escapes, NULL or a bare number). Returns value, next i.
local function Field(s, i)
    if s:sub(i, i) == "'" then
        local j, buf = i + 1, {}
        while true do
            local c = s:sub(j, j)
            if c == "" then return nil, j end
            if c == "\\" then buf[#buf + 1] = s:sub(j + 1, j + 1) j = j + 2
            elseif c == "'" then return table.concat(buf), j + 1
            else buf[#buf + 1] = c j = j + 1 end
        end
    end
    local j = s:find("[,)]", i)
    if not j then return nil, #s + 1 end
    return s:sub(i, j - 1), j
end

-- want = { [npc] = true }. Returns { [npc] = cleaned name }, or nil, error.
function MN.ReadNames(path, want)
    local fh = io.open(path, "rb")
    if not fh then return nil, "can't open " .. tostring(path) end
    local out = {}
    for line in fh:lines() do
        if line:sub(1, 38) == "INSERT INTO `creature_template` VALUES" then
            local i = 40
            while i <= #line do
                if line:sub(i, i) ~= "(" then
                    i = line:find("(", i, true)
                    if not i then break end
                end
                i = i + 1
                local vals, n = {}, 0
                while true do
                    local v, j = Field(line, i)
                    n = n + 1
                    if n <= 2 then vals[n] = v end
                    local c = line:sub(j, j)
                    i = j + 1
                    if c ~= "," then break end
                end
                local entry = tonumber(vals[1])
                if entry and want[entry] then out[entry] = MN.Clean(vals[2]) end
            end
        end
    end
    fh:close()
    return out
end

-- ------------------------------------------------------------------ the generated file
local function Quote(s) return ("%q"):format(s) end

function MN.Text(map, ids)
    local lines = {
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        "-- Copyright (C) 2026 gettic",
        "-- Generated by tools\\mob_names.lua from a CMaNGOS classic-db dump (https://github.com/cmangos/classic-db,",
        "-- GPL-3.0; creature_template Name, src = \"cmangos\"); do not edit. See CREDITS.txt.",
        "-- Command: luajit tools/mob_names.lua <ClassicDB.sql> (reads the mobs of AllinOneGuide\\Routes\\*.lua).",
        "-- NPC id -> English creature name, only for the mobs the shipped guide packs send you to. Used only by the",
        "-- target button (\"/targetexact <name>\", English clients only).",
        "local _, ns = ...",
        "ns.MobNames = {",
    }
    for _, id in ipairs(ids) do
        if map[id] then lines[#lines + 1] = ("    [%d] = %s,"):format(id, Quote(map[id])) end
    end
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
end

-- ------------------------------------------------------------------ command line
local function ReadFile(p)
    local fh = io.open(p, "rb")
    if not fh then return nil end
    local s = fh:read("*a")
    fh:close()
    return s
end

local function ListLua(dir)
    local out = {}
    local sep = package.config:sub(1, 1)
    local cmd = sep == "\\" and ('dir /b "' .. dir:gsub("/", "\\") .. '\\*.lua" 2>nul') or ('ls "' .. dir .. '"/*.lua 2>/dev/null')
    local p = io.popen(cmd)
    if p then
        for name in p:lines() do
            name = name:match("([^/\\]+)$")
            if name and name ~= "Connectors.lua" then out[#out + 1] = dir .. "/" .. name end
        end
        p:close()
    end
    table.sort(out)
    return out
end

function MN.Main(args)
    local sql, routes, outPath, check = nil, "AllinOneGuide/Routes", "AllinOneGuide/Data/MobNames.lua", false
    local i = 1
    while i <= #args do
        local a = args[i]
        if a == "--routes" then routes = args[i + 1] i = i + 1
        elseif a == "--out" then outPath = args[i + 1] i = i + 1
        elseif a == "--check" then check = true
        else sql = a end
        i = i + 1
    end
    if not sql then
        io.stderr:write("use: luajit tools/mob_names.lua <ClassicDB.sql> [--routes dir] [--out file] [--check]\n")
        return 2
    end
    local texts = {}
    for _, p in ipairs(ListLua(routes)) do texts[#texts + 1] = assert(ReadFile(p)) end
    local ids = MN.PackMobs(texts)
    local want = {}
    for _, id in ipairs(ids) do want[id] = true end
    local map, err = MN.ReadNames(sql, want)
    if not map then io.stderr:write(err .. "\n") return 1 end
    local text = MN.Text(map, ids)
    local found = 0
    for _ in pairs(map) do found = found + 1 end
    if check then
        if ReadFile(outPath) ~= text then
            io.stderr:write(outPath .. " is out of date (run tools/mob_names.lua)\n")
            return 1
        end
        print(("mob names: up to date (%d of %d pack mobs)"):format(found, #ids))
        return 0
    end
    local fh = assert(io.open(outPath, "wb"))
    fh:write(text)
    fh:close()
    print(("mob names: %d of %d pack mobs -> %s"):format(found, #ids, outPath))
    return 0
end

if argv[1] == "--lib" then return MN end
os.exit(MN.Main(argv))
