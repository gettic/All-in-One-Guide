-- Writes AllinOneGuide\Data\QuestLevels.lua: quest id -> quest level, only for the quests the shipped guide packs
-- have an accept step for. The quest giver check (Engine\QuestGiver.lua) uses it to leave grey quests alone
-- (the client may not list them), also when the accept step has no `level=` of its own.
-- Source: a LOCAL CMaNGOS classic-db SQL dump (https://github.com/cmangos/classic-db, GPL-3.0), read as TEXT
-- only (tools\import\questitems.lua's reader). Only quest_template `entry` and `QuestLevel` (numbers) are read.
-- Quests the dump doesn't have (Forever-only quests) or with no fixed level are left out (= no grey guard).
-- Run from the repository folder:
--   luajit tools/quest_levels.lua <ClassicDB.sql> [--routes AllinOneGuide/Routes] [--out AllinOneGuide/Data/QuestLevels.lua]
--   [--check]   write nothing; fail when the file differs (or is missing)
-- Library mode: local QL = loadfile("tools/quest_levels.lua")("--lib")
--   QL.PackQuests(texts) -> sorted ids     QL.Text(map, ids) -> file text
local argv = { ... }
local QL = { MAXLEVEL = 80 }

-- A compiled row: id|type|quest|npc|map|x|y|r|text|da|flags|cond|src|extra (texts never hold "|").
local function Fields(row)
    local f, i = {}, 1
    for part in (row .. "|"):gmatch("([^|]*)|") do f[i] = part i = i + 1 end
    return f
end

function QL.PackQuests(texts)
    local set = {}
    for _, text in ipairs(texts) do
        for row in text:gmatch('\n%s*"([^"\n]*)",?') do
            if row:find("|", 1, true) and select(2, row:gsub("|", "")) >= 12 then
                local f = Fields(row)
                local q = tonumber(f[3])
                if f[2] == "accept" and q and q > 0 then set[q] = true end
            end
        end
    end
    local ids = {}
    for id in pairs(set) do ids[#ids + 1] = id end
    table.sort(ids)
    return ids
end

function QL.Text(map, ids)
    local lines = {
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        "-- Copyright (C) 2026 gettic",
        "-- Generated by tools\\quest_levels.lua from a CMaNGOS classic-db dump (https://github.com/cmangos/classic-db,",
        "-- GPL-3.0; quest_template QuestLevel, src = \"cmangos\"); do not edit. See CREDITS.txt.",
        "-- Command: luajit tools/quest_levels.lua <ClassicDB.sql> (reads the accept steps of AllinOneGuide\\Routes\\*.lua).",
        "-- Quest id -> quest level, only for the quests the shipped guide packs accept. Used by the quest giver check",
        "-- (grey quests are never judged).",
        "local _, ns = ...",
        "ns.QuestLevels = {",
    }
    for _, id in ipairs(ids) do
        if map[id] then lines[#lines + 1] = ("    [%d] = %d,"):format(id, map[id]) end
    end
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
end

-- ------------------------------------------------------------------ command line
local function ReadFile(p)
    local fh = io.open(p, "rb")
    if not fh then return nil end
    local s = fh:read("*a")
    fh:close()
    return s
end

local function ListLua(dir)
    local out = {}
    local sep = package.config:sub(1, 1)
    local cmd = sep == "\\" and ('dir /b "' .. dir:gsub("/", "\\") .. '\\*.lua" 2>nul') or ('ls "' .. dir .. '"/*.lua 2>/dev/null')
    local p = io.popen(cmd)
    if p then
        for name in p:lines() do
            name = name:match("([^/\\]+)$")
            if name and name ~= "Connectors.lua" and name ~= "Spots.lua" then out[#out + 1] = dir .. "/" .. name end
        end
        p:close()
    end
    table.sort(out)
    return out
end

function QL.Main(args)
    local sql, routes, outPath, check = nil, "AllinOneGuide/Routes", "AllinOneGuide/Data/QuestLevels.lua", false
    local i = 1
    while i <= #args do
        local a = args[i]
        if a == "--routes" then routes = args[i + 1] i = i + 1
        elseif a == "--out" then outPath = args[i + 1] i = i + 1
        elseif a == "--check" then check = true
        else sql = a end
        i = i + 1
    end
    if not sql then
        io.stderr:write("use: luajit tools/quest_levels.lua <ClassicDB.sql> [--routes dir] [--out file] [--check]\n")
        return 2
    end
    local QI = assert(loadfile("tools/import/questitems.lua"))("--lib")
    local texts = {}
    for _, p in ipairs(ListLua(routes)) do texts[#texts + 1] = assert(ReadFile(p)) end
    local ids = QL.PackQuests(texts)
    local want = {}
    for _, id in ipairs(ids) do want[id] = true end
    local map = {}
    local ok, err = QI.Pass(sql, { quest_template = { cols = { "entry", "QuestLevel" }, fn = function(v)
        if want[v.entry] and v.QuestLevel >= 1 and v.QuestLevel <= QL.MAXLEVEL then map[v.entry] = v.QuestLevel end
    end } })
    if not ok then io.stderr:write(tostring(err) .. "\n") return 1 end
    local text = QL.Text(map, ids)
    local found = 0
    for _ in pairs(map) do found = found + 1 end
    if check then
        if ReadFile(outPath) ~= text then
            io.stderr:write(outPath .. " is out of date (run tools/quest_levels.lua)\n")
            return 1
        end
        print(("quest levels: up to date (%d of %d pack quests)"):format(found, #ids))
        return 0
    end
    local fh = assert(io.open(outPath, "wb"))
    fh:write(text)
    fh:close()
    print(("quest levels: %d of %d pack quests -> %s"):format(found, #ids, outPath))
    return 0
end

if argv[1] == "--lib" then return QL end
os.exit(QL.Main(argv))
