-- Writes AllinOneGuide\Data\ModelFit.lua: creature id -> how the 3D view frames it, for the creatures the 3D view
-- can show (the NPCs the shipped packs name, `npc` / `targetNpc`, and the quest mobs of Data\QuestMobs.lua).
-- Only creatures that are NOT framed like a standing humanoid are listed (humanoid / undead / demon / not in the
-- dump = the default fit by height):
--   "w" wide and low (beast, critter, mechanical): the camera starts a bit further back so it fits by width
--   "b" big (dragonkin, elemental, giant): the camera starts further back still
-- Source: a LOCAL CMaNGOS classic-db SQL dump (https://github.com/cmangos/classic-db, GPL-3.0), read as TEXT only.
-- Only `creature_template` Entry and CreatureType are read.
-- Run from the repository folder:
--   luajit tools/model_fit.lua <ClassicDB.sql> [--routes dir]... [--mobs AllinOneGuide/Data/QuestMobs.lua]
--   [--out AllinOneGuide/Data/ModelFit.lua] [--check]   (--check: write nothing; fail when the file differs)
-- Library mode: local MF = loadfile("tools/model_fit.lua")("--lib")
--   MF.Kind(creatureType) -> "w" / "b" / nil     MF.MobIds(text) -> ids     MF.Text(map, ids) -> file text
local argv = { ... }
local MI = assert(loadfile("tools/model_ids.lua"))("--lib")
local MF = {}

-- CreatureType (cmangos SharedDefines CreatureType): 1 beast, 2 dragonkin, 3 demon, 4 elemental, 5 giant,
-- 6 undead, 7 humanoid, 8 critter, 9 mechanical, 10 not specified, 11 totem
MF.KIND = { [1] = "w", [8] = "w", [9] = "w", [2] = "b", [4] = "b", [5] = "b" }
function MF.Kind(ctype) return MF.KIND[tonumber(ctype) or 0] end

-- The creature ids of Data\QuestMobs.lua's QuestMobInfo table (its text).
function MF.MobIds(text)
    local ids = {}
    local body = text and text:match("ns%.QuestMobInfo%s*=%s*(%b{})")
    if body then
        for id in body:gmatch("%[(%d+)%]%s*=") do ids[#ids + 1] = tonumber(id) end
    end
    return ids
end

-- want = { [id] = true }. Returns { [id] = "w" / "b" } (only the non-default ones), or nil, error.
function MF.Read(path, want)
    local fh = io.open(path, "rb")
    if not fh then return nil, "can't open " .. tostring(path) end
    local out = {}
    for line in fh:lines() do
        if line:sub(1, 38) == "INSERT INTO `creature_template` VALUES" then
            local i = 40
            while i <= #line do
                if line:sub(i, i) ~= "(" then
                    i = line:find("(", i, true)
                    if not i then break end
                end
                i = i + 1
                -- Entry (1) ... Scale (11), Family (12), CreatureType (13), then the rest up to ")"
                local vals, n = {}, 0
                while true do
                    local v, j = MI.Field(line, i)
                    n = n + 1
                    if n <= 13 then vals[n] = v end
                    local c = line:sub(j, j)
                    i = j + 1
                    if c ~= "," then break end
                end
                local entry = tonumber(vals[1])
                if entry and want[entry] then out[entry] = MF.Kind(vals[13]) end
            end
        end
    end
    fh:close()
    return out
end

function MF.Text(map, ids)
    local lines = {
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        "-- Copyright (C) 2026 gettic",
        "-- Generated by tools\\model_fit.lua from a CMaNGOS classic-db dump (https://github.com/cmangos/classic-db,",
        "-- GPL-3.0; creature_template CreatureType, src = \"cmangos\"); do not edit. See CREDITS.txt.",
        "-- Command: luajit tools/model_fit.lua <ClassicDB.sql> (the packs' NPCs + Data\\QuestMobs.lua's mobs).",
        "-- Creature id -> how the 3D view frames it (UI\\ModelView.lua MV.FIT): \"w\" wide and low (beast, critter,",
        "-- mechanical), \"b\" big (dragonkin, elemental, giant). Not listed = framed like a standing humanoid.",
        "local _, ns = ...",
        "ns.ModelFit = {",
    }
    local row = {}
    for _, id in ipairs(ids) do
        if map[id] then
            row[#row + 1] = ("[%d] = %q,"):format(id, map[id])
            if #row == 6 then
                lines[#lines + 1] = "    " .. table.concat(row, " ")
                row = {}
            end
        end
    end
    if #row > 0 then lines[#lines + 1] = "    " .. table.concat(row, " ") end
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
end

function MF.Main(args)
    local sql, routes, mobs, outPath, check = nil, {}, "AllinOneGuide/Data/QuestMobs.lua", "AllinOneGuide/Data/ModelFit.lua", false
    local i = 1
    while i <= #args do
        local a = args[i]
        if a == "--routes" then routes[#routes + 1] = args[i + 1] i = i + 1
        elseif a == "--mobs" then mobs = args[i + 1] i = i + 1
        elseif a == "--out" then outPath = args[i + 1] i = i + 1
        elseif a == "--check" then check = true
        else sql = a end
        i = i + 1
    end
    if not sql then
        io.stderr:write("use: luajit tools/model_fit.lua <ClassicDB.sql> [--routes dir] [--mobs file] [--out file] [--check]\n")
        return 2
    end
    if #routes == 0 then routes = { "AllinOneGuide/Routes", "AllinOneGuide_Horde/Routes", "AllinOneGuide_Alliance/Routes" } end
    local texts = {}
    for _, dir in ipairs(routes) do
        for _, p in ipairs(MI.ListLua(dir)) do texts[#texts + 1] = assert(MI.ReadFile(p)) end
    end
    local set = {}
    for _, id in ipairs(MI.PackNpcs(texts)) do set[id] = true end
    for _, id in ipairs(MF.MobIds(MI.ReadFile(mobs))) do set[id] = true end
    for _, id in ipairs(MI.ExtraNpcs()) do set[id] = true end
    local ids = {}
    for id in pairs(set) do ids[#ids + 1] = id end
    table.sort(ids)
    local map, err = MF.Read(sql, set)
    if not map then io.stderr:write(err .. "\n") return 1 end
    local text = MF.Text(map, ids)
    local counts = { w = 0, b = 0 }
    for _, k in pairs(map) do counts[k] = counts[k] + 1 end
    local summary = ("%d creatures: %d wide, %d big, the rest framed like a humanoid"):format(#ids, counts.w, counts.b)
    if check then
        if MI.ReadFile(outPath) ~= text then
            io.stderr:write(outPath .. " is out of date (run tools/model_fit.lua)\n")
            return 1
        end
        print("model fit: up to date (" .. summary .. ")")
        return 0
    end
    local fh = assert(io.open(outPath, "wb"))
    fh:write(text)
    fh:close()
    print("model fit: " .. summary .. " -> " .. outPath)
    return 0
end

if argv[1] == "--lib" then return MF end
os.exit(MF.Main(argv))
