-- Writes AllinOneGuide\Data\ModelIds.lua: NPC id -> creature display id, only for the NPCs the shipped guide
-- packs name (a step's `npc` or `targetNpc`). The 3D viewer (UI\ModelView.lua) asks the game by NPC id first
-- (PlayerModel:SetCreature); these display ids are only its fallback (SetDisplayInfo).
-- Source: a LOCAL CMaNGOS classic-db SQL dump (https://github.com/cmangos/classic-db, GPL-3.0), read as TEXT
-- only (never loaded into a database). Only `creature_template` Entry and ModelId1..4 are read (the first
-- non-zero one); no names, no texts, no spawn tables.
-- Run from the repository folder:
--   luajit tools/model_ids.lua <ClassicDB.sql> [--routes AllinOneGuide/Routes] [--out AllinOneGuide/Data/ModelIds.lua]
--   [--check]   write nothing; fail when the file differs (or is missing)
-- Library mode: local MI = loadfile("tools/model_ids.lua")("--lib")
--   MI.PackNpcs(texts) -> sorted ids     MI.ReadModels(path, want) -> { [npc] = display }
--   MI.Text(map, ids) -> file text      MI.Row(row) -> npc, targetNpc
local argv = { ... }
local MI = {}

-- ------------------------------------------------------------------ the NPCs the packs name
-- A compiled row: id|type|quest|npc|map|x|y|r|text|da|flags|cond|src|extra (texts never hold "|").
function MI.Row(row)
    local f, i = {}, 1
    for part in (row .. "|"):gmatch("([^|]*)|") do f[i] = part i = i + 1 end
    local npc = tonumber(f[4])
    local target = f[14] and tonumber(f[14]:match("targetNpc=(%d+)"))
    return npc, target
end

-- texts = the compiled Routes\*.lua files' contents. Returns the NPC ids, sorted.
function MI.PackNpcs(texts)
    local set = {}
    for _, text in ipairs(texts) do
        for row in text:gmatch('\n%s*"([^"\n]*)",?') do
            if row:find("|", 1, true) and select(2, row:gsub("|", "")) >= 12 then
                local a, b = MI.Row(row)
                if a and a > 0 then set[a] = true end
                if b and b > 0 then set[b] = true end
            end
        end
    end
    local ids = {}
    for id in pairs(set) do ids[#ids + 1] = id end
    table.sort(ids)
    return ids
end

-- ------------------------------------------------------------------ the SQL dump
-- One field from position i (a quoted string with \ escapes, NULL or a bare number). Returns value, next i
-- (on the "," / ")" after the field).
local function Field(s, i)
    if s:sub(i, i) == "'" then
        local j = i + 1
        while true do
            local c = s:sub(j, j)
            if c == "" then return nil, j end
            if c == "\\" then j = j + 2
            elseif c == "'" then return true, j + 1
            else j = j + 1 end
        end
    end
    local j = s:find("[,)]", i)
    if not j then return nil, #s + 1 end
    return s:sub(i, j - 1), j
end

-- want = { [npc] = true }. Returns { [npc] = display } (first non-zero ModelId1..4), or nil, error.
function MI.ReadModels(path, want)
    local fh = io.open(path, "rb")
    if not fh then return nil, "can't open " .. tostring(path) end
    local out = {}
    for line in fh:lines() do
        if line:sub(1, 38) == "INSERT INTO `creature_template` VALUES" then
            local i = 40
            while i <= #line do
                if line:sub(i, i) ~= "(" then
                    i = line:find("(", i, true)
                    if not i then break end
                end
                i = i + 1
                -- Entry, Name, SubName, MinLevel, MaxLevel, ModelId1..4, then the rest up to ")"
                local vals, n = {}, 0
                while true do
                    local v, j = Field(line, i)
                    n = n + 1
                    if n <= 9 then vals[n] = v end
                    local c = line:sub(j, j)
                    i = j + 1
                    if c ~= "," then break end
                end
                local entry = tonumber(vals[1])
                if entry and want[entry] then
                    for k = 6, 9 do
                        local m = tonumber(vals[k])
                        if m and m > 0 then out[entry] = m break end
                    end
                end
            end
        end
    end
    fh:close()
    return out
end

-- ------------------------------------------------------------------ the generated file
function MI.Text(map, ids)
    local lines = {
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        "-- Copyright (C) 2026 gettic",
        "-- Generated by tools\\model_ids.lua from a CMaNGOS classic-db dump (https://github.com/cmangos/classic-db,",
        "-- GPL-3.0; creature_template ModelId1..4, src = \"cmangos\"); do not edit. See CREDITS.txt.",
        "-- Command: luajit tools/model_ids.lua <ClassicDB.sql> (reads the NPC ids of AllinOneGuide\\Routes\\*.lua).",
        "-- NPC id -> creature display id, only for NPCs named in the shipped guide packs. The 3D viewer asks the",
        "-- game by NPC id first; a display id here is only its fallback.",
        "local _, ns = ...",
        "ns.ModelIds = {",
    }
    local row = {}
    for _, id in ipairs(ids) do
        if map[id] then
            row[#row + 1] = ("[%d] = %d,"):format(id, map[id])
            if #row == 6 then
                lines[#lines + 1] = "    " .. table.concat(row, " ")
                row = {}
            end
        end
    end
    if #row > 0 then lines[#lines + 1] = "    " .. table.concat(row, " ") end
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
end

-- ------------------------------------------------------------------ command line
local function ReadFile(p)
    local fh = io.open(p, "rb")
    if not fh then return nil end
    local s = fh:read("*a")
    fh:close()
    return s
end

local function ListLua(dir)
    local out = {}
    local sep = package.config:sub(1, 1)
    local cmd = sep == "\\" and ('dir /b "' .. dir:gsub("/", "\\") .. '\\*.lua" 2>nul') or ('ls "' .. dir .. '"/*.lua 2>/dev/null')
    local p = io.popen(cmd)
    if p then
        for name in p:lines() do
            name = name:match("([^/\\]+)$")
            if name and name ~= "Connectors.lua" then out[#out + 1] = dir .. "/" .. name end
        end
        p:close()
    end
    table.sort(out)
    return out
end

function MI.Main(args)
    -- v0.2.8: the packs live in their own addon folders since v0.2.5; --routes may be given more than once
    local sql, routes, outPath, check = nil, {}, "AllinOneGuide/Data/ModelIds.lua", false
    local i = 1
    while i <= #args do
        local a = args[i]
        if a == "--routes" then routes[#routes + 1] = args[i + 1] i = i + 1
        elseif a == "--out" then outPath = args[i + 1] i = i + 1
        elseif a == "--check" then check = true
        else sql = a end
        i = i + 1
    end
    if not sql then
        io.stderr:write("use: luajit tools/model_ids.lua <ClassicDB.sql> [--routes dir] [--out file] [--check]\n")
        return 2
    end
    if #routes == 0 then routes = { "AllinOneGuide/Routes", "AllinOneGuide_Horde/Routes", "AllinOneGuide_Alliance/Routes" } end
    local texts = {}
    for _, dir in ipairs(routes) do
        for _, p in ipairs(ListLua(dir)) do texts[#texts + 1] = assert(ReadFile(p)) end
    end
    local ids = MI.PackNpcs(texts)
    local want = {}
    for _, id in ipairs(ids) do want[id] = true end
    local map, err = MI.ReadModels(sql, want)
    if not map then io.stderr:write(err .. "\n") return 1 end
    local text = MI.Text(map, ids)
    local found = 0
    for _ in pairs(map) do found = found + 1 end
    if check then
        if ReadFile(outPath) ~= text then
            io.stderr:write(outPath .. " is out of date (run tools/model_ids.lua)\n")
            return 1
        end
        print(("model ids: up to date (%d of %d pack NPCs)"):format(found, #ids))
        return 0
    end
    local fh = assert(io.open(outPath, "wb"))
    fh:write(text)
    fh:close()
    print(("model ids: %d of %d pack NPCs -> %s"):format(found, #ids, outPath))
    return 0
end

if argv[1] == "--lib" then return MI end
os.exit(MI.Main(argv))
